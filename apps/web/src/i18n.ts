const DICTS: Record<Lang, Record<Key, string>> = { en, az };
const STORAGE_KEY = "claudestra.lang";

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "az") return saved;
  } catch {
    // Storage unavailable: fall through to the browser language.
  }
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("az") ? "az" : "en";
}

let current: Lang = initialLang();
if (typeof document !== "undefined") document.documentElement.lang = current;

export const lang = (): Lang => current;

export function setLang(next: Lang) {
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Not remembered in a private window; still switch for this page load.
  }
  current = next;
  window.location.reload();
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let text = DICTS[current][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

// Built-in agents get translated names; custom agents keep the name from their file.
export function agentName(id: string, fallback: string): string {
  const key = `agent.${id}` as Key;
  return key in en ? t(key) : fallback;
}

